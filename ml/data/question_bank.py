@dataclass(frozen=True)
class Question:
    question_id: str
    kc_id: str
    difficulty: int
    stem: str
    options: tuple[str, ...]
    answer_index: int

    @property
    def answer_text(self) -> str:
        return self.options[self.answer_index]


def build_question_bank() -> list[Question]:
    """构建题库，题目 ID 形如 Q001。"""
    bank: list[Question] = []
    for idx, (kc_id, diff, stem, options, ans) in enumerate(QUESTION_ROWS, start=1):
        if not 0 <= ans < len(options):
            raise ValueError(f"第 {idx} 题答案下标越界：{stem}")
        if len(options) != 4:
            raise ValueError(f"第 {idx} 题选项数不为 4：{stem}")
        bank.append(
            Question(
                question_id=f"Q{idx:03d}",
                kc_id=kc_id,
                difficulty=diff,
                stem=stem,
                options=tuple(options),
                answer_index=ans,
            )
        )
    return bank


def load_bank_from_csv(path: str | Path | None = None) -> list[Question]:
    """从 CSV 装载题库，列约定：question_id, kc_id, difficulty, stem, A, B, C, D, answer。

    用于后续把真实题库替换进来，不改动下游代码。
    """
    if path is None:
        path = "data/raw/questions.csv"
    rows: list[Question] = []
    with open(path, encoding="utf-8-sig", newline="") as f:
        for i, row in enumerate(csv.DictReader(f), start=1):
            rows.append(
                Question(
                    question_id=row.get("question_id") or f"Q{i:03d}",
                    kc_id=row["kc_id"],
                    difficulty=int(row.get("difficulty") or 1),
                    stem=row["stem"],
                    options=(row["A"], row["B"], row["C"], row["D"]),
                    answer_index=int(row["answer"]),
                )
            )
    return rows


def export_bank_csv(questions: Iterable[Question], path: str | Path) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["question_id", "kc_id", "difficulty", "stem", "A", "B", "C", "D", "answer"])
        for q in questions:
            w.writerow([q.question_id, q.kc_id, q.difficulty, q.stem, *q.options, q.answer_index])


